// node eval/run.js
// Writes eval/RESULTS.md and eval/results.json. Offline: no model is called.
// Column "patterns only" is the deterministic check alone. Column "model +
// patterns" uses on-device model output recorded from a real Chrome run in
// eval/nano-output.json (see eval/README in RESULTS.md); it is left out when
// that file does not exist.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { LETTERS } from './letters.js';
import { scoreLetter, summarise } from './score.js';
import { checkFacts } from '../src/core/pipeline.js';

const here = dirname(fileURLToPath(import.meta.url));
const nanoPath = join(here, 'nano-output.json');
const nano = existsSync(nanoPath) ? JSON.parse(readFileSync(nanoPath, 'utf8')) : null;

function run(detailsFor) {
  const scores = LETTERS.map((l) => ({ ...scoreLetter(l, detailsFor(l)), letter: l }));
  return { scores, summary: summarise(scores) };
}

const patterns = run(() => []);
const hybrid = nano ? run((l) => nano.letters?.[l.id]?.output?.personal_details || []) : null;

const pct = (a, b) => (b ? ((100 * a) / b).toFixed(1) + '%' : 'n/a');
const lines = [];
lines.push('# Evaluation: are personal details hidden before anything is sent?', '');
lines.push(`Generated by \`npm run eval\` on ${new Date().toISOString().slice(0, 10)}. ${LETTERS.length} made-up sample letters (eval/letters.js), ${patterns.summary.pii} labelled personal details, ${patterns.summary.keep} facts that must stay readable (amounts, deadlines).`, '');
lines.push('A detail counts as hidden only if it cannot be read anywhere in the text that would be sent, ignoring spacing and punctuation.', '');
lines.push('| Setup | Details hidden | Letters with nothing missed | Needed facts still readable |', '|---|---|---|---|');
const row = (name, s) => `| ${name} | ${s.hidden}/${s.pii} (${pct(s.hidden, s.pii)}) | ${s.lettersFullyHidden}/${s.letters} | ${s.kept}/${s.keep} (${pct(s.kept, s.keep)}) |`;
lines.push(row('Patterns only (no model; what a browser without Gemini Nano gets)', patterns.summary));
if (hybrid) lines.push(row(`On-device model + patterns (${nano.model || 'Gemini Nano'}, recorded ${nano.recorded || '?'})`, hybrid.summary));
else lines.push('| On-device model + patterns | not measured yet | | |');
lines.push('');

for (const [name, r] of [['Patterns only', patterns], ['On-device model + patterns', hybrid]]) {
  if (!r) continue;
  lines.push(`## ${name}: by kind`, '', '| Kind | Hidden |', '|---|---|');
  for (const [k, v] of Object.entries(r.summary.byKind).sort()) lines.push(`| ${k} | ${v.hidden}/${v.total} |`);
  lines.push('', `### ${name}: what was missed`, '');
  const missed = r.scores.flatMap((s) => s.missed.map((m) => `- ${s.id}: ${m.kind} "${m.text}"`));
  lines.push(...(missed.length ? missed : ['- nothing']), '');
  const lost = r.scores.flatMap((s) => s.lost.map((m) => `- ${s.id}: "${m}"`));
  lines.push(`### ${name}: needed facts hidden by mistake`, '', ...(lost.length ? lost : ['- none']), '');
}
if (nano) {
  // Facts card: amount and key date from the on-device model, before and after the "must be in the letter" check.
  const norm = (x) => String(x).toLowerCase().replace(/[£\s]/g, '');
  const tally = { amount: { right: 0, wrong: 0, dropped: 0, empty: 0 }, deadline: { right: 0, wrong: 0, dropped: 0, empty: 0 } };
  const wrong = [];
  for (const l of LETTERS) {
    const raw = nano.letters[l.id].output;
    const shown = checkFacts(l.text, raw);
    for (const key of ['amount', 'deadline']) {
      const ok = (v) => l.facts[key].some((a) => norm(v).includes(norm(a)));
      if (!String(raw[key] || '').trim()) tally[key].empty++;
      else if (!shown[key]) {
        tally[key].dropped++;
        wrong.push(`- ${l.id}: ${key} "${raw[key]}" is not in the letter: not shown`);
      } else if (ok(shown[key])) tally[key].right++;
      else {
        tally[key].wrong++;
        wrong.push(`- ${l.id}: ${key} "${shown[key]}" is in the letter but is not the main one (expected ${l.facts[key].join(' or ')}): shown`);
      }
    }
  }
  lines.push('## Facts card (amount and key date from the on-device model)', '');
  lines.push('The app shows a fact only if its words are in the letter. Counted against our labels in eval/letters.js:', '');
  lines.push('| Fact | Shown and right | Shown but not the main one | Not in the letter, so not shown | Model gave none |', '|---|---|---|---|---|');
  for (const key of ['amount', 'deadline']) lines.push(`| ${key} | ${tally[key].right}/${LETTERS.length} | ${tally[key].wrong} | ${tally[key].dropped} | ${tally[key].empty} |`);
  lines.push('', ...(wrong.length ? wrong : ['- all right']), '');
  console.log('facts', JSON.stringify(tally));
  lines.push('## On-device model run', '');
  lines.push(`Recorded ${nano.recorded} in ${nano.browser || 'Chrome'} through the Firebase AI Logic SDK (mode only_on_device). Time per letter: ${Object.entries(nano.letters).map(([id, v]) => `${id} ${(v.ms / 1000).toFixed(1)} s`).join(', ')}.`, '');
}
lines.push('## Limits', '', '- The patterns were written while looking at these same letters, so the patterns-only figure is optimistic for letters we have not seen.', '- Ten letters written by us is a small, friendly sample. Real letters vary more (scans, tables, handwriting, Welsh).', '- The labels are ours. A detail we did not think to label is not counted.', '- Names without a title and address lines without a street word cannot be found by patterns; that is the on-device model\'s job, and the user sees the text before it is sent and can hide anything else by hand.', '');

writeFileSync(join(here, 'RESULTS.md'), lines.join('\n'));
writeFileSync(
  join(here, 'results.json'),
  JSON.stringify({ patterns: patterns.summary, hybrid: hybrid?.summary || null, missedPatterns: patterns.scores.map((s) => ({ id: s.id, missed: s.missed, lost: s.lost })), missedHybrid: hybrid?.scores.map((s) => ({ id: s.id, missed: s.missed, lost: s.lost })) || null }, null, 1)
);
console.log(lines.slice(4, 9).join('\n'));
console.log('\nmissed (patterns only):');
for (const s of patterns.scores) if (s.missed.length || s.lost.length) console.log(' ', s.id, s.missed.map((m) => m.kind + ':' + m.text), 'lost:', s.lost);
