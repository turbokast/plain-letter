// node eval/cloud.js
// Scores a recorded cloud run (eval/cloud-output.json, written from a real
// Chrome run of the app with a Firebase project connected) and writes
// eval/CLOUD-RESULTS.md. Offline: no model is called here.
//
// Per letter it checks:
//   sent     - was any labelled personal detail still readable in the exact text sent?
//   amount   - does the cloud answer (summary, meaning, if ignored, options) state the main amount?
//   deadline - ... and the date or period to act by?
//   reply    - does the reply draft use the person's placeholders (so details can be filled back)?
//   unknown  - placeholders in the answer that were never the person's own

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { LETTERS } from './letters.js';
import { visible } from './score.js';

const here = dirname(fileURLToPath(import.meta.url));
const run = JSON.parse(readFileSync(join(here, 'cloud-output.json'), 'utf8'));

const norm = (s) => String(s).toLowerCase().replace(/\s+/g, ' ');
const mentions = (text, values) => values.some((v) => norm(text).includes(norm(v)) || norm(text).includes(norm(v).replace(/\.00$/, '')));

const rows = [];
for (const letter of LETTERS) {
  const r = run.letters[letter.id];
  if (!r) continue;
  const a = r.answer || {};
  const body = [a.summary, ...(a.what_it_means || []), a.if_ignored, ...(a.options || []).flatMap((o) => [o.title, o.detail])].join('\n');
  rows.push({
    id: letter.id,
    source: r.source,
    sentChars: r.sent.length,
    leaked: letter.pii.filter((p) => visible(r.sent, p.text)).map((p) => p.text),
    amount: mentions(body, letter.facts.amount),
    deadline: mentions(body, letter.facts.deadline),
    replyPlaceholders: (String(a.reply_draft || '').match(/\[[A-Z_]+_\d+\]/g) || []).length,
    unknown: r.unknown || [],
    explainMs: r.explainMs,
  });
}

const n = rows.length;
const count = (f) => rows.filter(f).length;
const ms = rows.map((r) => r.explainMs).sort((x, y) => x - y);
const lines = [
  '# Cloud step: recorded run',
  '',
  `Generated by \`node eval/cloud.js\` from \`eval/cloud-output.json\` (recorded ${run.recorded}, ${run.browser}; ${run.cloud_model}). ${run.note}`,
  '',
  `- Letters answered from the cloud: ${count((r) => r.source === 'cloud')} of ${n}`,
  `- Letters where a labelled personal detail was still readable in the text sent: ${count((r) => r.leaked.length)} of ${n}`,
  `- Answer states the main amount: ${count((r) => r.amount)} of ${n}; the date or period to act by: ${count((r) => r.deadline)} of ${n}`,
  `- Reply draft uses the person's placeholders (so details are filled back on the device): ${count((r) => r.replyPlaceholders > 0)} of ${n}`,
  `- Answers with a placeholder that was never the person's own: ${count((r) => r.unknown.length)} of ${n}`,
  `- Cloud step time: ${ms[0]} to ${ms[ms.length - 1]} ms (median ${ms[Math.floor(n / 2)]} ms)`,
  '',
  '| Letter | Source | Chars sent | Still readable in sent text | Amount | Deadline | Placeholders in reply | Unknown placeholders | ms |',
  '|---|---|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.id} | ${r.source} | ${r.sentChars} | ${r.leaked.join(', ') || 'none'} | ${r.amount ? 'yes' : 'no'} | ${r.deadline ? 'yes' : 'no'} | ${r.replyPlaceholders} | ${r.unknown.join(', ') || 'none'} | ${r.explainMs} |`),
  '',
  'Amount and deadline are a plain text match against the acceptable values in `eval/letters.js`; a correct answer in other words counts as a miss. Whether the explanation is right in substance was not scored by this script.',
  '',
];
writeFileSync(join(here, 'CLOUD-RESULTS.md'), lines.join('\n'));
